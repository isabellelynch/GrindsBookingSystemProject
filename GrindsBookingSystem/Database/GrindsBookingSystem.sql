-- Classes and bookings. Semester numbers are worked out from today's date (the same way as
-- Class.GetCurrentSemester() in the app), so the schedule always has classes when you open it.
DECLARE
    cur  NUMBER := TO_NUMBER(TO_CHAR(SYSDATE, 'YY') ||
                             CASE WHEN EXTRACT(MONTH FROM SYSDATE) <= 6 THEN '1' ELSE '2' END);
    prev NUMBER;

    -- (PL/SQL needs all variables declared before the helper functions below)
    aoife   NUMBER;
    ciaran  NUMBER;
    niamh   NUMBER;
    darragh NUMBER;
    sinead  NUMBER;

    c_maths   NUMBER;
    c_english NUMBER;
    c_irish   NUMBER;
    c_maths2  NUMBER;
    c_acc     NUMBER;
    c_science NUMBER;
    c_jcmaths NUMBER;
    c_full    NUMBER;
    c_old     NUMBER;

    FUNCTION tutor(p_email VARCHAR2) RETURN NUMBER IS
        v NUMBER;
    BEGIN
        SELECT TutorID INTO v FROM Tutors WHERE Email = p_email;
        RETURN v;
    END;

    FUNCTION subject(p_cat VARCHAR2, p_level VARCHAR2, p_desc VARCHAR2) RETURN NUMBER IS
        v NUMBER;
    BEGIN
        SELECT SubjectID INTO v FROM Subjects
        WHERE SubjectCategory = p_cat AND SubjectLevel = p_level AND Description = p_desc;
        RETURN v;
    END;

    FUNCTION student(p_email VARCHAR2) RETURN NUMBER IS
        v NUMBER;
    BEGIN
        SELECT StudentID INTO v FROM Students WHERE Email = p_email;
        RETURN v;
    END;

    FUNCTION add_class(p_day NUMBER, p_time NUMBER, p_tutor NUMBER, p_room NUMBER,
                       p_sem NUMBER, p_subject NUMBER) RETURN NUMBER IS
        v NUMBER;
    BEGIN
        INSERT INTO Classes (Day, Time, TutorID, CurrentEnrollment, RoomNo, SemesterNo, SubjectID)
        VALUES (p_day, p_time, p_tutor, 0, p_room, p_sem, p_subject)
        RETURNING ClassID INTO v;
        RETURN v;
    END;

    PROCEDURE book(p_student NUMBER, p_class NUMBER, p_days_ago NUMBER) IS
    BEGIN
        INSERT INTO Bookings (StudentID, ClassID, BookingDate)
        VALUES (p_student, p_class, TRUNC(SYSDATE) - p_days_ago);
    END;

BEGIN
    aoife   := tutor('aoife.byrne@grindsschool.ie');
    ciaran  := tutor('ciaran.obrien@grindsschool.ie');
    niamh   := tutor('niamh.kelly@grindsschool.ie');
    darragh := tutor('darragh.walsh@grindsschool.ie');
    sinead  := tutor('sinead.murphy@grindsschool.ie');

    -- previous semester (e.g. 262 -> 261, 261 -> 252)
    IF MOD(cur, 10) = 2 THEN
        prev := cur - 1;
    ELSE
        prev := cur - 9;
    END IF;

    -- this semester's timetable
    c_maths   := add_class(1, 16, aoife,   1, cur, subject('LC', 'HL', 'Maths'));
    c_english := add_class(1, 17, ciaran,  1, cur, subject('LC', 'HL', 'English'));
    c_irish   := add_class(2, 16, niamh,   1, cur, subject('LC', 'HL', 'Irish'));
