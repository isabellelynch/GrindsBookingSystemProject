    c_jcmaths := add_class(4, 17, darragh, 2, cur, subject('JC', 'HL', 'Maths'));
    c_full    := add_class(5, 15, ciaran,  3, cur, subject('LC', 'HL', 'English'));  -- Room 3 holds 3, booked full below

    -- a class from last semester (doesn't show on the schedule)
    c_old     := add_class(1, 16, aoife,   1, prev, subject('LC', 'HL', 'Maths'));

    book(student('emma.ryan@example.com'),      c_maths,   10);
