    book(student('conor.mccarthy@example.com'), c_old,    400);

    -- CurrentEnrollment = number of active bookings for each class
    UPDATE Classes c
    SET CurrentEnrollment = (SELECT COUNT(*) FROM Bookings b
                             WHERE b.ClassID = c.ClassID AND b.Status = 'A');
END;
