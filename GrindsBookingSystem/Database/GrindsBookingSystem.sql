-- Grinds Booking System - Oracle database setup
-- Creates every table the C# app uses, with keys, checks and sample data.
--
-- Run it as your own Oracle user (SQL Developer: open this file and press
-- F5 "Run Script"; SQL*Plus: @GrindsBookingSystem.sql).
-- Needs Oracle 12c or later (identity columns).
--
-- WARNING: running it again drops the tables and starts from scratch.
