-- ---------- remove old tables (errors are ignored if they don't exist) ----------
BEGIN
    FOR t IN (SELECT table_name FROM user_tables
              WHERE table_name IN ('BOOKINGS', 'CLASSES', 'TUTOR_SUBJECTS', 'ROOMS',
                                   'SUBJECTS', 'STUDENTS', 'TUTORS', 'TUTORRATES'))
    LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
    END LOOP;
END;
/

-- ---------- tables ----------
-- Column ORDER matters: the app reads some tables with SELECT * and column numbers.

CREATE TABLE TutorRates (
    RateCode    VARCHAR2(3)   PRIMARY KEY,           -- SNR / JNR / NEW
    HourlyRate  NUMBER(5)     NOT NULL CHECK (HourlyRate >= 0),
    Description VARCHAR2(50)  NOT NULL
);

CREATE TABLE Tutors (
    TutorID   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    FirstName VARCHAR2(50)  NOT NULL,
    Surname   VARCHAR2(50)  NOT NULL,
    Email     VARCHAR2(254) NOT NULL UNIQUE,
    PhoneNo   VARCHAR2(11)  NOT NULL,                -- 08X-XXXXXXX
    RateCode  VARCHAR2(3)   NOT NULL REFERENCES TutorRates (RateCode),
    Status    CHAR(1)       DEFAULT 'A' NOT NULL CHECK (Status IN ('A', 'I'))   -- Active / Inactive
);

CREATE TABLE Students (
    StudentID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    FirstName VARCHAR2(50)  NOT NULL,
    Surname   VARCHAR2(50)  NOT NULL,
    Email     VARCHAR2(254) NOT NULL UNIQUE,
    PhoneNo   VARCHAR2(11)  NOT NULL,
    Status    CHAR(1)       DEFAULT 'A' NOT NULL CHECK (Status IN ('A', 'I'))
);

CREATE TABLE Subjects (
    SubjectID       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    SubjectCategory VARCHAR2(2)  NOT NULL CHECK (SubjectCategory IN ('LC', 'JC')),  -- Leaving / Junior Cert
    SubjectLevel    VARCHAR2(2)  NOT NULL CHECK (SubjectLevel IN ('HL', 'OL')),     -- Higher / Ordinary
    Description     VARCHAR2(50) NOT NULL,
    CONSTRAINT uq_subject UNIQUE (SubjectCategory, SubjectLevel, Description)
);

CREATE TABLE Tutor_Subjects (
    TutorID   NUMBER NOT NULL REFERENCES Tutors (TutorID),
    SubjectID NUMBER NOT NULL REFERENCES Subjects (SubjectID),
    CONSTRAINT pk_tutor_subjects PRIMARY KEY (TutorID, SubjectID)
);

CREATE TABLE Rooms (
    RoomNo      NUMBER(1)    PRIMARY KEY CHECK (RoomNo BETWEEN 1 AND 9),  -- the app reads room numbers as one digit
    Description VARCHAR2(50) NOT NULL,
    Capacity    NUMBER(3)    NOT NULL CHECK (Capacity > 0)
);

CREATE TABLE Classes (
    ClassID           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    Day               NUMBER(1) NOT NULL CHECK (Day BETWEEN 1 AND 5),     -- 1 = Monday ... 5 = Friday
    Time              NUMBER(2) NOT NULL CHECK (Time BETWEEN 9 AND 17),   -- start hour
    TutorID           NUMBER    NOT NULL REFERENCES Tutors (TutorID),
    CurrentEnrollment NUMBER(3) DEFAULT 0 NOT NULL CHECK (CurrentEnrollment >= 0),
    RoomNo            NUMBER(1) NOT NULL REFERENCES Rooms (RoomNo),
    SemesterNo        NUMBER(3) NOT NULL,                                 -- e.g. 262 = second half of 2026
    SubjectID         NUMBER    NOT NULL REFERENCES Subjects (SubjectID),
    Status            CHAR(1)   DEFAULT 'A' NOT NULL CHECK (Status IN ('A', 'C'))   -- Active / Cancelled
);

CREATE TABLE Bookings (
    BookingID   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    StudentID   NUMBER  NOT NULL REFERENCES Students (StudentID),
    ClassID     NUMBER  NOT NULL REFERENCES Classes (ClassID),
    BookingDate DATE    DEFAULT SYSDATE NOT NULL,
    Status      CHAR(1) DEFAULT 'A' NOT NULL CHECK (Status IN ('A', 'C'))   -- Active / Cancelled
);

